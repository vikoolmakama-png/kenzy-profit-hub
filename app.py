@app.route("/admin/panel")
def admin_panel():
    if not session.get("is_admin"):
        return redirect(url_for("admin_login"))

    conn = db()
    try:
        users = conn.execute(
            """SELECT id, full_name, username, phone, created_at
               FROM users ORDER BY id DESC"""
        ).fetchall()

        transactions = conn.execute(
            """SELECT t.id, t.user_id, t.kind, t.amount, t.details,
                      t.status, t.created_at, u.full_name, u.username
               FROM transactions t
               LEFT JOIN users u ON u.id = t.user_id
               ORDER BY t.id DESC LIMIT 300"""
        ).fetchall()

        pending_count = conn.execute(
            """SELECT COUNT(*) FROM transactions
               WHERE lower(status) = 'pending'"""
        ).fetchone()[0]

        balances = {}
        for user in users:
            balances[user["id"]] = 0.0

        approved = conn.execute(
            """SELECT user_id, kind, amount FROM transactions
               WHERE lower(status) = 'approved'"""
        ).fetchall()

        for tx in approved:
            uid = tx["user_id"]
            if uid not in balances:
                continue
            kind = (tx["kind"] or "").lower()
            amount = float(tx["amount"] or 0)
            if "deposit" in kind:
                balances[uid] += amount
            elif "withdraw" in kind:
                balances[uid] -= amount

    finally:
        conn.close()

    return render_template(
        "admin_panel.html",
        users=users,
        transactions=transactions,
        pending_count=pending_count,
        balances=balances
    )


@app.route("/admin/transaction/<int:transaction_id>/<action>", methods=["POST"])
def admin_transaction_action(transaction_id, action):
    if not session.get("is_admin"):
        return redirect(url_for("admin_login"))

    if action not in ("approve", "reject"):
        flash("Invalid transaction action.", "error")
        return redirect(url_for("admin_panel"))

    conn = db()
    try:
        conn.execute("BEGIN IMMEDIATE")
        tx = conn.execute(
            """SELECT id, user_id, kind, amount, status
               FROM transactions WHERE id = ?""",
            (transaction_id,)
        ).fetchone()

        if not tx:
            conn.rollback()
            flash("Transaction not found.", "error")
            return redirect(url_for("admin_panel"))

        if (tx["status"] or "").lower() != "pending":
            conn.rollback()
            flash("This request has already been processed.", "error")
            return redirect(url_for("admin_panel"))

        kind = (tx["kind"] or "").lower()
        amount = float(tx["amount"] or 0)

        if amount <= 0:
            conn.rollback()
            flash("Invalid transaction amount.", "error")
            return redirect(url_for("admin_panel"))

        if action == "approve" and "withdraw" in kind:
            totals = conn.execute(
                """SELECT kind, amount FROM transactions
                   WHERE user_id = ? AND lower(status) = 'approved'""",
                (tx["user_id"],)
            ).fetchall()

            balance = 0.0
            for item in totals:
                approved_kind = (item["kind"] or "").lower()
                value = float(item["amount"] or 0)
                if "deposit" in approved_kind:
                    balance += value
                elif "withdraw" in approved_kind:
                    balance -= value

            if balance < amount:
                conn.rollback()
                flash("Withdrawal rejected: insufficient available balance.", "error")
                return redirect(url_for("admin_panel"))

        if action == "approve" and not (
            "deposit" in kind or "withdraw" in kind
        ):
            conn.rollback()
            flash("Only deposit and withdrawal requests can be approved here.", "error")
            return redirect(url_for("admin_panel"))

        new_status = "approved" if action == "approve" else "rejected"
        conn.execute(
            "UPDATE transactions SET status = ? WHERE id = ? AND lower(status) = 'pending'",
            (new_status, transaction_id)
        )
        conn.commit()
        flash(f"Transaction #{transaction_id} {new_status}.", "success")

    except Exception:
        conn.rollback()
        app.logger.exception("Admin transaction action failed")
        flash("Could not process this request. Check the server log.", "error")
    finally:
        conn.close()

    return redirect(url_for("admin_panel"))


