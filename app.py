@app.route("/withdraw", methods=["GET", "POST"])
def withdraw():
    if "user_id" not in session:
        return redirect(url_for("login"))

    if request.method == "POST":
        account = request.form.get("account", "").strip()
        account_name = request.form.get("account_name", "").strip()
        bank = request.form.get("bank", "").strip()

        try:
            amount = float(request.form.get("amount", "0"))
            if not 1000 <= amount <= 100000000:
                raise ValueError
        except ValueError:
            flash("Enter a valid withdrawal amount.", "error")
            return redirect(url_for("withdraw"))

        if (not account.isdigit() or len(account) != 10
                or not account_name or len(account_name) > 100
                or not bank or len(bank) > 100):
            flash("Check the bank account details. Use a 10-digit account number.", "error")
            return redirect(url_for("withdraw"))

        import json
        conn = db()

        try:
            conn.execute("BEGIN IMMEDIATE")

            approved = conn.execute(
                """SELECT kind, amount FROM transactions
                   WHERE user_id = ? AND lower(status) = 'approved'""",
                (session["user_id"],)
            ).fetchall()

            balance = 0.0

            for tx in approved:
                kind = (tx["kind"] or "").lower()
                value = float(tx["amount"] or 0)

                if "deposit" in kind:
                    balance += value
                elif "withdraw" in kind or "plan_purchase" in kind:
                    balance -= value

            rewards = conn.execute(
                """SELECT COALESCE(SUM(amount), 0)
                   FROM daily_rewards
                   WHERE user_id = ? AND lower(status) = 'approved'""",
                (session["user_id"],)
            ).fetchone()[0]

            balance += float(rewards or 0)

            pending_withdrawals = conn.execute(
                """SELECT COALESCE(SUM(amount), 0)
                   FROM transactions
                   WHERE user_id = ?
                     AND lower(status) = 'pending'
                     AND lower(kind) LIKE '%withdraw%'""",
                (session["user_id"],)
            ).fetchone()[0]

            balance -= float(pending_withdrawals or 0)
            balance = max(0.0, balance)

            if amount > balance:
                conn.rollback()
                flash(
                    f"Insufficient available balance. Your balance is ₦{balance:,.2f}.",
                    "error"
                )
                return redirect(url_for("withdraw"))

            conn.execute(
                """INSERT INTO transactions
                   (user_id, kind, amount, details)
                   VALUES (?, ?, ?, ?)""",
                (
                    session["user_id"],
                    "WITHDRAWAL",
                    amount,
                    json.dumps({
                        "account": account,
                        "account_name": account_name,
                        "bank": bank
                    })
                )
            )

            conn.commit()

        except Exception:
            conn.rollback()
            raise

        finally:
            conn.close()

        flash("Withdrawal request submitted for review. Payment has not been made.", "success")
        return redirect(url_for("dashboard"))

    return render_template("withdraw.html")


