@app.route("/dashboard")
def dashboard():
    if "user_id" not in session:
        return redirect(url_for("login"))

    user_id = session["user_id"]

    # Record eligible simulated rewards before calculating the balance.
    process_daily_rewards(user_id)

    conn = db()
    try:
        user = conn.execute(
            "SELECT id, full_name, username, phone FROM users WHERE id = ?",
            (user_id,)
        ).fetchone()

        if not user:
            session.clear()
            return redirect(url_for("login"))

        transactions = conn.execute(
            """SELECT id, kind, amount, details, status, created_at
               FROM transactions
               WHERE user_id = ?
               ORDER BY id DESC
               LIMIT 100""",
            (user_id,)
        ).fetchall()

        approved = conn.execute(
            """SELECT kind, amount FROM transactions
               WHERE user_id = ? AND lower(status) = 'approved'""",
            (user_id,)
        ).fetchall()

        balance = 0.0
        for tx in approved:
            kind = (tx["kind"] or "").lower()
            amount = float(tx["amount"] or 0)

            if "deposit" in kind:
                balance += amount
            elif "withdraw" in kind or "plan_purchase" in kind:
                balance -= amount

        rewards = conn.execute(
            """SELECT COALESCE(SUM(amount), 0)
               FROM daily_rewards
               WHERE user_id = ? AND lower(status) = 'approved'""",
            (user_id,)
        ).fetchone()[0]

        balance += float(rewards or 0)

        pending_withdrawals = conn.execute(
            """SELECT COALESCE(SUM(amount), 0)
               FROM transactions
               WHERE user_id = ?
                 AND lower(status) = 'pending'
                 AND lower(kind) LIKE '%withdraw%'""",
            (user_id,)
        ).fetchone()[0]

        balance -= float(pending_withdrawals or 0)

        return render_template(
            "dashboard.html",
            user=user,
            transactions=transactions,
            balance=max(0.0, balance)
        )
    finally:
        conn.close()

