class HybridRow(dict):
    """Support both row['column'] and row[0] access."""
    def __init__(self, names, values):
        super().__init__(zip(names, values))
        self._values = values

    def __getitem__(self, key):
        if isinstance(key, int):
            return self._values[key]
        return super().__getitem__(key)


def hybrid_row_factory(cursor):
    names = [column.name for column in cursor.description]

    def make_row(values):
        return HybridRow(names, values)

    return make_row


class PostgreSQLCursor:
    def __init__(self, cursor, lastrowid=None):
        self._cursor = cursor
        self.lastrowid = lastrowid

    def __getattr__(self, name):
        return getattr(self._cursor, name)


class PostgreSQLConnection:
    def __init__(self, connection):
        self._connection = connection

    def execute(self, sql, params=()):
        sql = sql.strip()
        params = tuple(params or ())

        # PostgreSQL equivalent of SQLite's table-column inspection.
        if re.search(r"PRAGMA\s+table_info\(users\)", sql, re.I):
            sql = """
                SELECT column_name AS name
                FROM information_schema.columns
                WHERE table_schema = current_schema()
                  AND table_name = %s
                ORDER BY ordinal_position
            """
            params = ("users",)

        sql = re.sub(r"\bBEGIN\s+IMMEDIATE\b", "BEGIN", sql, flags=re.I)
        sql = sql.replace(
            "INTEGER PRIMARY KEY AUTOINCREMENT",
            "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
        )
        sql = re.sub(r"\bREAL\b", "DOUBLE PRECISION", sql, flags=re.I)

        # PostgreSQL uses %s placeholders instead of SQLite question marks.
        sql = sql.replace("?", "%s")

        ignore_conflicts = bool(
            re.match(r"INSERT\s+OR\s+IGNORE\s+", sql, re.I)
        )
        if ignore_conflicts:
            sql = re.sub(
                r"INSERT\s+OR\s+IGNORE\s+",
                "INSERT ",
                sql,
                count=1,
                flags=re.I
            )

        # Preserve the existing referral-code format using PostgreSQL SQL.
        sql = sql.replace(
            "printf('%05d', id)",
            "LPAD(id::text, 5, '0')"
        )

        # Retrieve generated IDs where the application expects lastrowid.
        match = re.match(r"INSERT\s+INTO\s+(users|transactions|daily_rewards)\b",
                         sql, re.I)
        needs_id = bool(match) and not re.search(r"\bRETURNING\b", sql, re.I)

        if ignore_conflicts:
            sql += " ON CONFLICT DO NOTHING"

        if needs_id:
            sql += " RETURNING id"

        cursor = self._connection.execute(sql, params)
        generated_id = None

        if needs_id:
            row = cursor.fetchone()
            if row is not None:
                generated_id = row["id"]

        return PostgreSQLCursor(cursor, generated_id)

    def commit(self):
        return self._connection.commit()

    def rollback(self):
        return self._connection.rollback()

    def close(self):
        return self._connection.close()


def db():
    if not DATABASE_URL:
        raise RuntimeError(
            "DATABASE_URL is missing. Configure your PostgreSQL "
            "connection in the hosting environment."
        )

    database_url = DATABASE_URL
    if database_url.startswith("postgres://"):
        database_url = "postgresql://" + database_url[len("postgres://"):]

    connection = psycopg.connect(
        database_url,
        row_factory=hybrid_row_factory
    )
    return PostgreSQLConnection(connection)


def process_daily_rewards(user_id):
    """Record simulated plan rewards once per eligible day after noon in Nigeria."""
    nigeria = timezone(timedelta(hours=1))
    now = datetime.now(nigeria)

    # No reward is recorded before noon Nigeria time.
    if now.hour < 12:
        return

    today = now.date()
    conn = db()

    try:
        conn.execute("BEGIN IMMEDIATE")

        plans = conn.execute(
            """SELECT id, amount, created_at
               FROM transactions
               WHERE user_id = ?
                 AND lower(kind) = 'plan_purchase'
                 AND lower(status) = 'approved'
               ORDER BY id""",
            (user_id,)
        ).fetchall()

        for plan in plans:
            try:
                activated = plan["created_at"]
                if isinstance(activated, str):
                    activated = datetime.fromisoformat(activated)
                start_date = activated.date()
            except (TypeError, ValueError):
                start_date = today

            # Do not credit the activation date itself.
            reward_date = start_date + timedelta(days=1)

            while reward_date <= today:
                reward_amount = round(float(plan["amount"]) * 0.07, 2)

                conn.execute(
                    """INSERT OR IGNORE INTO daily_rewards
                       (user_id, plan_transaction_id, reward_date, amount, status)
                       VALUES (?, ?, ?, ?, 'APPROVED')""",
                    (
                        user_id,
                        plan["id"],
                        reward_date.isoformat(),
                        reward_amount
                    )
                )

                reward_date += timedelta(days=1)

        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def process_all_users_daily_rewards():
    """Process eligible daily rewards for every registered user."""
    conn = db()
    try:
        users = conn.execute("SELECT id FROM users").fetchall()
        user_ids = [row["id"] for row in users]
    finally:
        conn.close()

    for user_id in user_ids:
        try:
            process_daily_rewards(user_id)
        except Exception:
            app.logger.exception(
                "Daily reward processing failed for user %s", user_id
            )




def init_db():
    conn = db()
    try:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS users (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                full_name TEXT NOT NULL,
                username TEXT NOT NULL UNIQUE,
                phone TEXT NOT NULL UNIQUE,
                referral_code TEXT,
                password TEXT NOT NULL,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                referred_by INTEGER
            )
        """)

        columns = {
            row["name"]
            for row in conn.execute("PRAGMA table_info(users)").fetchall()
        }
        if "referred_by" not in columns:
            conn.execute(
                "ALTER TABLE users ADD COLUMN referred_by INTEGER"
            )

        # Give every existing account a consistent, unique referral code.
        conn.execute("""
            UPDATE users
            SET referral_code = 'KPH' || printf('%05d', id)
            WHERE referral_code IS NULL OR TRIM(referral_code) = ''
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS welcome_bonuses (
                user_id INTEGER PRIMARY KEY,
                transaction_id INTEGER NOT NULL UNIQUE
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS referral_rewards (
                plan_transaction_id INTEGER PRIMARY KEY,
                inviter_user_id INTEGER NOT NULL,
                referred_user_id INTEGER NOT NULL,
                reward_amount REAL NOT NULL,
                transaction_id INTEGER NOT NULL UNIQUE
            )
        """)


        conn.execute("""
            CREATE TABLE IF NOT EXISTS daily_rewards (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL,
                plan_transaction_id BIGINT NOT NULL,
                reward_date DATE NOT NULL,
                amount DOUBLE PRECISION NOT NULL,
                status TEXT NOT NULL DEFAULT 'APPROVED',
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                UNIQUE (plan_transaction_id, reward_date)
            )
        """)

        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()



